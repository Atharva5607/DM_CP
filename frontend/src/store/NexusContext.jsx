import { createContext, useCallback, useContext, useEffect, useMemo, useRef, useState } from 'react';
import { api } from '../services/api';
import { demoGraph, loadDemo } from '../demo';

export const NexusContext = createContext(null);
export const useNexus = () => useContext(NexusContext);

const DEMO_MSG = 'Demo snapshot mode replays the four built-in scenarios. Start the backend to run custom events and edit the graph.';

/**
 * Single source of truth for the UI. In live mode everything mirrors backend responses.
 * In demo mode (backend unreachable) it serves a frozen snapshot generated by backend/scripts/export_demo.py.
 */
export function NexusProvider({ children }) {
  const [boot, setBoot] = useState('loading'); // loading | ready | offline
  const [mode, setMode] = useState('live'); // live | demo
  const [scenarios, setScenarios] = useState([]);
  const [graph, setGraph] = useState(null);
  const [simulation, setSimulation] = useState(null);
  const [recs, setRecs] = useState(null);
  const [analytics, setAnalytics] = useState(null);
  const [vulnerability, setVulnerability] = useState(null);
  const [resolved, setResolved] = useState([]);
  const [comparison, setComparison] = useState(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);
  const demo = useRef(null);

  const guard = useCallback(async (fn) => {
    setBusy(true);
    setError(null);
    try {
      return await fn();
    } catch (e) {
      setError(e.message);
      return null;
    } finally {
      setBusy(false);
    }
  }, []);

  const clearAnalysis = () => {
    setSimulation(null);
    setRecs(null);
    setAnalytics(null);
    setVulnerability(null);
    setResolved([]);
    setComparison(null);
  };

  const bootstrap = useCallback(async () => {
    setBoot('loading');
    setMode('live');
    try {
      const [s, g] = await Promise.all([api.scenarios(), api.graph()]);
      setScenarios(s);
      setGraph(g);
      clearAnalysis();
      setBoot('ready');
    } catch (e) {
      setError(e.message);
      setBoot('offline');
    }
  }, []);

  useEffect(() => {
    bootstrap();
  }, [bootstrap]);

  const showDemoScenario = useCallback((id) => {
    const d = demo.current;
    const s = d.byScenario[id];
    setGraph(demoGraph(d, id));
    setSimulation(s.simulation);
    setRecs(s.recs);
    setAnalytics(s.analytics);
    setVulnerability(null);
    setResolved([]);
    setComparison(null);
    return demoGraph(d, id);
  }, []);

  const enterDemo = useCallback(async () => {
    demo.current = await loadDemo();
    setMode('demo');
    setError(null);
    setScenarios(demo.current.scenarios);
    showDemoScenario(demo.current.scenarios[0].id);
    setBoot('ready');
  }, [showDemoScenario]);

  const loadScenario = useCallback(
    (id) =>
      guard(async () => {
        if (mode === 'demo') return showDemoScenario(id);
        const g = await api.loadScenario(id);
        clearAnalysis();
        setGraph(g);
        return g;
      }),
    [guard, mode, showDemoScenario]
  );

  /** Run a cascade for an inline event object. */
  const runEvent = useCallback(
    (event) =>
      guard(async () => {
        if (mode === 'demo') {
          const s = demo.current.byScenario[graph.scenario];
          const p = s.events[0];
          const same = event.type === p.type && event.zone === p.zone && [...event.target_nodes].sort().join() === [...p.target_nodes].sort().join()
            && [...event.target_edges].sort().join() === [...p.target_edges].sort().join() && Number(event.severity) === p.severity;
          if (!same) throw new Error(DEMO_MSG);
          setSimulation(s.simulation);
          setRecs(s.recs);
          setAnalytics(s.analytics);
          setResolved([]);
          setComparison(null);
          return s.simulation;
        }
        const sim = await api.simulate({ event });
        const [r, a] = await Promise.all([api.recommendations(), api.analytics()]);
        setSimulation(sim);
        setRecs(r);
        setAnalytics(a);
        setResolved([]);
        setComparison(null);
        return sim;
      }),
    [guard, mode, graph]
  );

  const mitigate = useCallback(
    (mitigations) =>
      guard(async () => {
        if (mode === 'demo') {
          const s = demo.current.byScenario[graph.scenario];
          const plan = s.recs.plan.mitigations;
          if (JSON.stringify(mitigations) !== JSON.stringify(plan)) throw new Error('Demo snapshot mode can apply the recommended plan only. Start the backend to try individual actions.');
          setSimulation(s.plan_result.simulation);
          setResolved(s.plan_result.resolved_nodes);
          setComparison({ before: s.plan_result.before_risk, after: s.plan_result.after_risk });
          return s.plan_result;
        }
        const out = await api.mitigate(mitigations);
        setSimulation(out.simulation);
        setResolved(out.resolved_nodes);
        setComparison({ before: out.before_risk, after: out.after_risk });
        setAnalytics(await api.analytics());
        return out;
      }),
    [guard, mode, graph]
  );

  const loadVulnerability = useCallback(
    () => guard(async () => setVulnerability(mode === 'demo' ? demo.current.vulnerability : await api.vulnerability())),
    [guard, mode]
  );

  /** Builder edits. Each one refreshes the graph and clears stale results. */
  const edit = useCallback(
    (fn) =>
      guard(async () => {
        if (mode === 'demo') throw new Error(DEMO_MSG);
        await fn();
        clearAnalysis();
        setGraph(await api.graph());
        return true;
      }),
    [guard, mode]
  );

  const value = useMemo(
    () => ({
      boot, mode, scenarios, graph, simulation, recs, analytics, vulnerability, resolved, comparison, busy, error,
      bootstrap, enterDemo, loadScenario, runEvent, mitigate, loadVulnerability, edit, setError,
    }),
    [boot, mode, scenarios, graph, simulation, recs, analytics, vulnerability, resolved, comparison, busy, error,
      bootstrap, enterDemo, loadScenario, runEvent, mitigate, loadVulnerability, edit]
  );

  return <NexusContext.Provider value={value}>{children}</NexusContext.Provider>;
}
